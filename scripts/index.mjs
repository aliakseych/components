import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CATALOG, ROOT, files, listComponents, listTemplates, readMeta } from "./lib.mjs";

const cell = (value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ");

const components = listComponents().map((component) => {
  const previews = files(join(component.dir, "previews"), /\.png$/).map(
    (name) => `components/${component.id}/previews/${name}`,
  );
  return {
    id: component.id,
    category: component.category,
    slug: component.slug,
    path: `components/${component.id}`,
    ...readMeta(component),
    demos: component.demos,
    previews,
  };
});

mkdirSync(CATALOG, { recursive: true });
const tagList = JSON.parse(readFileSync(join(ROOT, "tags.json"), "utf8"));
const tags = Object.fromEntries(
  Object.entries(tagList).map(([tag, description]) => [
    tag,
    {
      description,
      components: components.filter((item) => item.tags.includes(tag)).map((item) => item.id),
    },
  ]),
);
const categoryList = JSON.parse(readFileSync(join(ROOT, "categories.json"), "utf8"));
const categories = Object.fromEntries(
  Object.entries(categoryList).map(([id, info]) => [
    id,
    { ...info, components: components.filter((item) => item.category === id).map((item) => item.id) },
  ]),
);
const blocks = files(join(ROOT, "blocks"), /\.json$/).map((name) => ({
  id: name.slice(0, -5),
  ...JSON.parse(readFileSync(join(ROOT, "blocks", name), "utf8")),
}));
const templates = listTemplates().map((template) => ({
  id: template.id,
  slug: template.slug,
  path: template.id,
  ...template.meta,
  previews: files(join(template.dir, "previews"), /\.png$/).map((name) => `${template.id}/previews/${name}`),
}));
writeFileSync(
  join(CATALOG, "index.json"),
  `${JSON.stringify({ categories, blocks, tags, templates, components }, null, 2)}\n`,
);

const rows = components.map((component) => {
  const thumbnail =
    component.previews.find((path) => path.endsWith(".desktop.light.png")) ??
    component.previews[0];
  const image = thumbnail ? `<img src="../${thumbnail}" width="200" alt="">` : "";
  return `| ${image} | [${cell(component.name)}](../${component.path}) | ${cell(component.summary)} | ${cell(component.useWhen.join("; "))} | ${cell(component.avoidWhen.join("; "))} | ${cell(component.status)} |`;
});

const templateRows = templates.map((template) => {
  const thumbnail = template.previews.find((path) => path.includes(".mobile.light.")) ?? template.previews[0];
  const image = thumbnail ? `<img src="../${thumbnail}" width="120" alt="">` : "";
  return `| ${image} | [${cell(template.name)}](../${template.path}) | ${cell(template.summary)} | ${cell(template.screens.length)} | ${cell(template.useWhen.join("; "))} | ${cell(template.status)} |`;
});

writeFileSync(
  join(CATALOG, "CATALOG.md"),
  `# Catalog

Generated by \`pnpm run index\`. Do not edit by hand.

## Templates

Whole apps you start a project from. Each runs on its own (\`pnpm dev\` in its folder) and on sample data.

| Preview | Template | Summary | Screens | Use when | Status |
| --- | --- | --- | --- | --- | --- |
${templateRows.join("\n")}

## Components

| Preview | Component | Summary | Use when | Avoid when | Status |
| --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`,
);
console.log(`Indexed ${components.length} component(s) and ${templates.length} template(s)`);
